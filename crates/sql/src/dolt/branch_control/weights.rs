/// weights returns the explicit weights, parsed on first use.
fn weights() -> &'static [(u32, i32)] {
    static PARSED: OnceLock<Vec<(u32, i32)>> = OnceLock::new();
    PARSED.get_or_init(|| {
        WEIGHTS
            .as_chunks::<8>()
            .0
            .iter()
            .map(|c| {
                let code = u32::from_be_bytes([c[0], c[1], c[2], c[3]]);
                (code, u32::from_be_bytes([c[4], c[5], c[6], c[7]]) as i32)
            })
            .collect()
    })
}

/// ai_ci returns a character's weight, as go-mysql-server's Utf8mb4_0900_ai_ci_RuneWeight does.
pub fn ai_ci(c: char) -> i32 {
    let code = c as u32;
    if let Ok(i) = weights().binary_search_by_key(&code, |&(k, _)| k) {
        return weights()[i].1;
    }
    let found = RANGES.partition_point(|&(_, end, _)| end < code);
    match RANGES.get(found) {
        Some(&(start, _, offset)) if start <= code => code as i32 + offset,
        _ if (917760..=917999).contains(&code) => 0,
        _ => i32::MAX,
    }
}
